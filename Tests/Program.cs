using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using EdlChapters.lib;
using MediaBrowser.Model.Entities;
class Program
{
    static int tests;
    static void Check(bool ok,string name) { if(!ok) throw new Exception(name); tests++; Console.WriteLine("PASS "+name); }
    static long T(decimal seconds) => (long)(seconds*10000000);
    static ChapterInfo C(string name,decimal seconds,MarkerType type=MarkerType.Chapter) => new ChapterInfo {Name=name,StartPositionTicks=T(seconds),MarkerType=type};
    static string Key(ChapterInfo c) => c.Name+"|"+c.StartPositionTicks+"|"+c.MarkerType;
    static void Main(string[] args)
    {
        Check(!ThumbnailTrigger.ShouldRequest(false,true,true),"thumbnail setting defaults off / disabled does not trigger");
        Check(!ThumbnailTrigger.ShouldRequest(true,false,true),"preview does not trigger thumbnail extraction");
        Check(!ThumbnailTrigger.ShouldRequest(true,true,false),"unchanged import does not trigger thumbnail extraction");
        Check(ThumbnailTrigger.ShouldRequest(true,true,true),"verified changed import requests thumbnails when enabled");
        var ranges=EdlParser.Parse(new[]{"# EDL", "10.125\t20.25\t3", "19 25 0", "30 40 1", "45 50 2"});
        Check(ranges.Count==1 && ranges[0].Start==T(10.125m) && ranges[0].End==T(25),"invariant EDL parsing, overlap merging, mute/scene exclusion");
        System.Globalization.CultureInfo.CurrentCulture=new System.Globalization.CultureInfo("de-DE");
        Check(EdlParser.Parse(new[]{"1.25 2.50 3"})[0].Start==T(1.25m),"decimal parsing independent of server locale");
        foreach(var invalid in new[]{"20 10 3","-1 10 3","1 2 4","NaN 20 3","","1 2"})
        {
            bool rejected=false;try {EdlParser.Parse(new[]{invalid});}catch(ArgumentException){rejected=true;}
            Check(rejected,"reject invalid EDL: "+invalid);
        }
        int removed;
        var plan=EdlChapterPlan.Build(new List<ChapterInfo>(),ranges,T(100),false,out removed);
        Check(plan.Count==3 && plan[0].StartPositionTicks==0 && plan[1].Name=="Advertisement" && plan[2].StartPositionTicks==T(25),"empty item gets programme/start/end chapters");
        var prior=new List<ChapterInfo>{C("Chapter 1",0),C("Chapter 2",15),C("Chapter 3",30),C("IntroStart",5,MarkerType.IntroStart)};
        bool refused=false;try{EdlChapterPlan.Build(prior,ranges,T(100),false,out removed);}catch(ArgumentException){refused=true;}
        Check(refused,"existing ordinary chapters require explicit replacement");
        plan=EdlChapterPlan.Build(prior,ranges,T(100),true,out removed);
        Check(removed==1 && plan.Contains(prior[0]) && plan.Contains(prior[2]) && plan.Contains(prior[3]),"retain existing outside chapters and intro metadata objects");
        Check(plan.Zip(plan.Skip(1),(a,b)=>a.StartPositionTicks<=b.StartPositionTicks).All(x=>x),"chapters sorted");
        var repeat=EdlChapterPlan.Build(plan,ranges,T(100),true,out removed);
        Check(plan.Select(Key).SequenceEqual(repeat.Select(Key)),"repeat import is idempotent");
        bool markerRefused=false;
        try{EdlChapterPlan.Build(new List<ChapterInfo>{C("IntroEnd",18,MarkerType.IntroEnd)},ranges,T(100),true,out removed);}catch(ArgumentException){markerRefused=true;}
        Check(markerRefused,"never overwrite an overlapping intro marker");
        if(args.Length>0)
        {
            var actual=EdlParser.Parse(File.ReadAllLines(args[0]));
            var imported=EdlChapterPlan.Build(new List<ChapterInfo>(),actual,T(3903.494767m),false,out removed);
            Check(actual.Count==6 && imported.Count==12,"provided Cuomo EDL: six breaks, twelve chapter boundaries");
            var autogenerated=Enumerable.Range(0,14).Select(i=>C("Chapter "+(i+1),i*300)).ToList();
            var converted=EdlChapterPlan.Build(autogenerated,actual,T(3903.494767m),true,out removed);
            Check(actual.All(range=>{
                var index=converted.FindIndex(c=>c.Name=="Advertisement" && c.StartPositionTicks==range.Start);
                return index>=0 && index+1<converted.Count && converted[index+1].StartPositionTicks==range.End;
            }),"all six advertisements jump to the correct next chapter despite original five-minute markers");
            Console.WriteLine("Cuomo chapter boundaries:");
            foreach(var c in imported)Console.WriteLine(TimeSpan.FromTicks(c.StartPositionTicks)+" "+c.Name);
        }
        ThumbnailQueueTest.Run();
        Console.WriteLine(tests+" checks passed.");
    }
}
